#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""生成本机证据快照: data_manifest.sha256 + env_fingerprint.json + MANIFEST.sha256

不修改原始训练产物，但生成模式会覆盖三个证据清单。历史快照不应在
外部语料漂移后直接重生成；fresh clone 请运行 verify_tracked.py。

用法:
  python3 evidence/make_manifest.py --check    # 复验已有历史清单, 不重写
  python3 evidence/make_manifest.py --write    # 明确覆盖本机快照
"""
import argparse
import hashlib
import json
import os
import platform
import re
import sqlite3
import subprocess
import sys
from datetime import datetime, timezone

PA = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
EV = os.path.join(PA, "evidence")
VENV_SP = "/data1/paper_agent_venv/lib/python3.12/site-packages"

# 外部语料 (不在 paper_agent/ 内, 但训练/检索依赖, 必须一并对账)
EXTERNAL = [
    ("/data1/arxiv_incremental/arxiv.db", "arXiv 增量库 (SQLite)"),
    ("/data1/arxiv_incremental/arxiv.index", "arXiv 增量库向量索引 (MiniLM-384)"),
    ("/data1/arxiv_incremental/arxiv_ids.json", "arXiv 增量库 id 映射"),
    ("/data1/arxiv_incremental/meta.json", "arXiv 增量库元信息"),
    ("/data1/peS2o_kb_faiss/papers.db", "peS2o 基座库 (SQLite, 只读)"),
    ("/data1/peS2o_kb_faiss/papers.index", "peS2o 基座向量索引 (MiniLM-384)"),
    ("/data1/peS2o_kb_faiss/paper_ids.txt", "peS2o 基座 id 映射"),
    ("/data1/models/Qwen3-4B/config.json", "基座模型 config"),
    ("/data1/models/Qwen3-4B/model.safetensors.index.json", "基座模型权重索引"),
    ("/data1/peS2o_kb_faiss/models/all-MiniLM-L6-v2/config.json", "检索 embedding 模型 config"),
    ("/data1/peS2o_kb_faiss/models/all-MiniLM-L6-v2/model.safetensors",
     "检索 embedding 模型权重"),
]


def sha256(path, buf=1 << 20):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            b = f.read(buf)
            if not b:
                break
            h.update(b)
    return h.hexdigest()


def walk(root):
    out = []
    for dp, dn, fn in os.walk(root):
        dn[:] = [d for d in dn if d != "__pycache__"]
        for n in sorted(fn):
            p = os.path.join(dp, n)
            out.append(p)
    return sorted(out)


def build_data_manifest():
    """工作区内全部文件 + 外部语料, 逐项 sha256 + 字节数。"""
    rows = []
    for p in walk(PA):
        rel = os.path.relpath(p, PA)
        if rel.startswith("evidence" + os.sep):
            continue
        rows.append((sha256(p), os.path.getsize(p), "internal", rel))
    for p, desc in EXTERNAL:
        if os.path.exists(p):
            rows.append((sha256(p), os.path.getsize(p), "external",
                         "%s  # %s" % (p, desc)))
        else:
            rows.append(("MISSING", 0, "external", "%s  # %s" % (p, desc)))
    rows.sort(key=lambda r: (r[2], r[3]))
    lines = ["# sha256  size_bytes  scope  path",
             "# scope: internal=paper_agent/ 内; external=外部依赖语料/模型",
             "# generated by paper_agent/evidence/make_manifest.py (只读)"]
    lines += ["%s  %d  %s  %s" % r for r in rows]
    with open(os.path.join(EV, "data_manifest.sha256"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")
    return rows


def installed_versions():
    out = {}
    if os.path.isdir(VENV_SP):
        for d in os.listdir(VENV_SP):
            m = re.match(r"(.+?)-([0-9][^-]*)\.dist-info$", d)
            if m:
                out[m.group(1).lower().replace("-", "_")] = m.group(2)
    return out


def recorded_versions():
    """reports/dpo_env_freeze.txt 里人工登记的版本 (用于对账, 不作为事实)。"""
    rec = {}
    p = os.path.join(PA, "reports", "dpo_env_freeze.txt")
    if os.path.exists(p):
        for line in open(p, encoding="utf-8"):
            line = line.strip()
            if "==" in line:
                k, v = line.split("==", 1)
                rec[k.lower().replace("-", "_")] = v
    return rec


def requirements_parse():
    req = {}
    p = os.path.join(PA, "requirements.txt")
    for line in open(p, encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        m = re.match(r"^([A-Za-z0-9_.\-]+)\s*(==|>=|<=|>|<)\s*(.+)$", line)
        if m:
            req[m.group(1).lower().replace("-", "_")] = (m.group(2), m.group(3).strip())
    return req


def sh(cmd):
    try:
        return subprocess.run(cmd, shell=True, capture_output=True,
                              text=True, timeout=30).stdout.strip()
    except Exception:
        return ""


def gpu_info():
    q = sh("nvidia-smi --query-gpu=name,memory.total,driver_version "
           "--format=csv,noheader")
    return q.splitlines()[0].strip() if q else "unavailable"


def corpus_counts():
    out = {}
    for label, db in (("arxiv_incremental", "/data1/arxiv_incremental/arxiv.db"),
                      ("peS2o_base", "/data1/peS2o_kb_faiss/papers.db")):
        if not os.path.exists(db):
            out[label] = None
            continue
        try:
            con = sqlite3.connect("file:%s?mode=ro" % db, uri=True)
            out[label] = con.execute("SELECT count(*) FROM papers").fetchone()[0]
            con.close()
        except Exception as e:
            out[label] = "error: %s" % e
    return out


def env_fingerprint():
    act = installed_versions()
    rec = recorded_versions()
    req = requirements_parse()

    mism = []
    for k, v in sorted(rec.items()):
        a = act.get(k)
        if a != v:
            mism.append({"package": k, "recorded_in_dpo_env_freeze": v,
                         "actual_in_venv": a})

    viol = []
    for k, (op, ver) in sorted(req.items()):
        a = act.get(k)
        if a is None:
            viol.append({"package": k, "requirement": "%s%s" % (op, ver),
                         "actual": None, "issue": "not installed"})
            continue
        if op == "<":
            major_minor = ver.split(".")[:2]
            if not a.startswith(".".join(major_minor)):
                viol.append({"package": k, "requirement": "<%s" % ver,
                             "actual": a, "issue": "version ceiling violated"})
        elif op == ">=":
            def tup(s):
                return tuple(int(x) for x in re.findall(r"\d+", s)[:3])
            if tup(a) < tup(ver):
                viol.append({"package": k, "requirement": ">=%s" % ver,
                             "actual": a, "issue": "below floor"})

    return {
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "note": "本文件由 make_manifest.py 从实测状态生成。dpo_env_freeze.txt 的登记值"
                "仅作对账用，不视为事实来源；事实来源是 actual_in_venv。",
        "platform": {
            "python": platform.python_version(),
            "kernel": platform.release(),
            "machine": platform.machine(),
            "gpu": gpu_info(),
            "hf_env": {k: os.environ.get(k) for k in
                       ("HF_HOME", "HF_HUB_CACHE", "HF_DATASETS_CACHE", "TORCH_HOME")},
            "venv": "/data1/paper_agent_venv",
            "base_model_local": "/data1/models/Qwen3-4B",
            "base_model_hub_id": "Qwen/Qwen3-4B",
            "base_model_resolvable_by_id": False,
            "base_model_resolvable_by_path": True,
        },
        "corpus_row_counts": corpus_counts(),
        "packages_actual": dict(sorted(act.items())),
        "packages_recorded_in_dpo_env_freeze": dict(sorted(rec.items())),
        "recorded_vs_actual_mismatches": mism,
        "requirements_vs_actual_violations": viol,
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="复验 data_manifest.sha256, 不重写清单")
    ap.add_argument("--write", action="store_true",
                    help="明确覆盖本机 data/environment/evidence 快照")
    a = ap.parse_args()

    if a.check == a.write:
        ap.error("choose exactly one of --check or --write")

    os.makedirs(EV, exist_ok=True)

    if a.check:
        mp = os.path.join(EV, "data_manifest.sha256")
        bad = miss = 0
        for line in open(mp, encoding="utf-8"):
            if line.startswith("#") or not line.strip():
                continue
            h, size, scope, path = line.rstrip("\n").split("  ", 3)
            real = path.split("  # ")[0]
            if scope == "internal":
                real = os.path.join(PA, real)
            if not os.path.exists(real):
                print("MISSING  %s" % real)
                miss += 1
                continue
            if sha256(real) != h:
                print("CHANGED  %s" % real)
                bad += 1
        print("[check] changed=%d missing=%d" % (bad, miss))
        return 1 if (bad or miss) else 0

    rows = build_data_manifest()
    fp = env_fingerprint()
    with open(os.path.join(EV, "env_fingerprint.json"), "w", encoding="utf-8") as f:
        json.dump(fp, f, ensure_ascii=False, indent=2)

    # 证据包自身也对账 (evidence/ 下所有文件)
    own = []
    for p in sorted(walk(EV)):
        rel = os.path.relpath(p, EV)
        if rel == "MANIFEST.sha256":
            continue
        own.append("%s  %s" % (sha256(p), rel))
    with open(os.path.join(EV, "MANIFEST.sha256"), "w", encoding="utf-8") as f:
        f.write("\n".join(own) + "\n")

    n_int = sum(1 for r in rows if r[2] == "internal")
    n_ext = sum(1 for r in rows if r[2] == "external")
    print("[manifest] internal=%d external=%d -> evidence/data_manifest.sha256"
          % (n_int, n_ext))
    print("[env] recorded/actual mismatches=%d, requirements violations=%d"
          % (len(fp["recorded_vs_actual_mismatches"]),
             len(fp["requirements_vs_actual_violations"])))
    print("[env] corpus rows: %s" % fp["corpus_row_counts"])
    return 0


if __name__ == "__main__":
    sys.exit(main())
